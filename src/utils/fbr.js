/**
 * Shared constants for the internal FBR/PRAL-style workflow.
 *
 * Nothing here talks to FBR. The lists are deliberately small and explicit so
 * the generated payload never pretends to encode a legal classification that
 * the business has not confirmed with an accountant.
 */

export const FBR_PROVINCES = Object.freeze([
    'Punjab',
    'Sindh',
    'Khyber Pakhtunkhwa',
    'Balochistan',
    'Islamabad Capital Territory',
    'Gilgit-Baltistan',
    'Azad Jammu and Kashmir',
]);

export const FBR_REGISTRATION_TYPES = Object.freeze(['Registered', 'Unregistered']);

export const FBR_SALE_TYPES = Object.freeze(['Taxable', 'Exempt', 'Zero-rated', 'Third Schedule']);

/**
 * The FBR DI API expects its published saleType strings, not the short labels
 * used by the form. Keep this map as the single translation point.
 */
export const FBR_SALE_TYPE_VALUES = Object.freeze({
    Taxable: 'Goods at standard rate (default)',
    Exempt: 'Exempt goods',
    'Zero-rated': 'Goods at zero-rate',
    'Third Schedule': '3rd Schedule Goods',
});

export function fbrSaleTypeValue(saleType) {
    if (!saleType) return '';
    return FBR_SALE_TYPE_VALUES[saleType] ?? saleType;
}

/** Reverses the published FBR string back to the short form label. */
export const FBR_SALE_TYPE_INTERNAL = Object.freeze(
    Object.fromEntries(Object.entries(FBR_SALE_TYPE_VALUES).map(([internal, published]) => [published, internal]))
);

export function fbrSaleTypeInternal(saleType) {
    if (!saleType) return '';
    return FBR_SALE_TYPE_INTERNAL[saleType] ?? saleType;
}

export const FBR_MOCK_VERSION = 'PRAL v1.12';

export const FBR_MOCK_DISCLAIMER =
    'This invoice has been processed through the FBR invoicing workflow of this system. The reference is generated by this system.';

export const FBR_MOCK_STATUS = Object.freeze({
    VALIDATED: 'mock_validated',
    SUBMITTED: 'mock_submitted',
});

export function fbrStatusLabel(status) {
    if (status === FBR_MOCK_STATUS.VALIDATED) return 'Validated';
    if (status === FBR_MOCK_STATUS.SUBMITTED) return 'Submitted';
    return 'Not Submitted to FBR';
}
